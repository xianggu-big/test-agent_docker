from mod_separate_paren_groups import separate_paren_groups





def check(separate_paren_groups):
    assert separate_paren_groups('(()()) ((())) () ((())()())') == [
        '(()())', '((()))', '()', '((())()())'
    ]
    assert separate_paren_groups('() (()) ((())) (((())))') == [
        '()', '(())', '((()))', '(((())))'
    ]
    assert separate_paren_groups('(()(())((())))') == [
        '(()(())((())))'
    ]
    assert separate_paren_groups('( ) (( )) (( )( ))') == ['()', '(())', '(()())']

check(separate_paren_groups)
check(separate_paren_groups)
print('OFFICIAL-OK')
